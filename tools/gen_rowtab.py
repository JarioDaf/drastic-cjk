"""gen_rowtab.py -- derive ROWTAB straight from the vendor's menu tree.

An earlier version ran only the five builders it already knew, which is exactly how it
missed the real 配置按键 page: that page looks like its own 额外按键 sub-page
and the two share a tail and a title.  This version runs the vendor's own
main-menu builder (0x7F3E0) and walks the tree it returns, so a page can only
be missing if it is not in the program at all.

    collect(mu)   -> [(label_off, src_y, page, row), ...]
    python gen_rowtab.py > rowtab.inc

A row whose label is not one of the injected strings (the vendor's "A", "B",
"X", "Y" on the key page) is emitted as OFF_ANY: it carries no table offset
and is resolved at runtime from the page the previous row established.
"""
import struct, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
for _p in (HERE, os.path.join(ROOT, "harness"), os.path.join(ROOT, "assets")):
    if _p not in sys.path:
        sys.path.insert(0, _p)
import config as C
import page_sim as P
from unicorn import *
from unicorn.arm64_const import *

# measured on the PATCHED binary: the labels the runtime is handed are the
# ones the patch installed, so the offsets below are the real ones.
BIN     = os.environ.get("CJK") or C.build("drastic.cjk")
STRTAB  = 0x152000
MENU_SZ = 1555
OFF_ANY = 0xFFFF

# label path from the root -> page id used by cjk.c's PAGES[]
PATHS = {
    (): 0,                                      # MAIN
    ("配置固件",): 1,
    ("配置按键", "额外按键"): 2,
    ("更改选项", "视频选项"): 3,
    ("更改选项",): 4,
    ("配置按键",): 5,
}

def u32(mu, a): return struct.unpack("<I", P.rd(mu, a, 4))[0]
def u64(mu, a): return struct.unpack("<Q", P.rd(mu, a, 8))[0]

def s_at(mu, a, n=40):
    try: b = bytes(mu.mem_read(a, n))
    except Exception: return "?"
    b = b.split(b"\0")[0]
    try: return b.decode("gbk")
    except Exception: return b.decode("latin1")

def collect(mu):
    """walk the vendor's menu tree and return [(label_off, src_y, page, row)]"""
    rows, seen = [], set()

    def walk(p, path, depth):
        if depth > 3 or p in seen or (p & 7) or p < 0x2000020: return
        seen.add(p)
        try: tail = u64(mu, p)
        except Exception: return
        if not (0x79000 <= tail < 0x7b000): return
        if path not in PATHS:
            raise SystemExit("unknown page in the tree: %r" % (path,))
        pid = PATHS[path]
        cnt = u32(mu, p + 0x14); arr = u64(mu, p + 0x20)
        print("/* page %d %-22r x_origin=%-4d count=%-2d tail=0x%x */"
              % (pid, "/".join(path), u32(mu, p + 0x10), cnt, tail), file=sys.stderr)
        for i in range(cnt):
            np = u64(mu, arr + 8 * i)
            if np == 0: continue
            lab = u64(mu, np); key = u32(mu, np + 8)
            off = (lab - STRTAB) if STRTAB <= lab < STRTAB + MENU_SZ else OFF_ANY
            rows.append((off, (key * 8) & 0xFFFF, pid, i))
            print("/*   row %-2d y=%-4d off=%-6s rend=0x%-6x %r */"
                  % (i, key * 8, ("0x%03x" % off) if off != OFF_ANY else "VENDOR",
                     u64(mu, np + 0x10), s_at(mu, lab)), file=sys.stderr)
            sub = u64(mu, np + 0x30)
            if sub and 0x2000020 <= sub < 0x3000000:
                walk(sub, path + (s_at(mu, lab).strip(),), depth + 1)

    P._bump[0] = 0x1000
    mu.mem_write(P.BIG, b"\0" * 0x800)
    mu.mem_write(P.BIG + 8, struct.pack("<Q", P.SCRATCH))
    walk(P.run(mu, 0x7F3E0, [P.BIG]), (), 0)
    rows.sort(key=lambda r: (r[2], r[3]))       # canonical: by page, then row
    return rows

def main():
    pm = P.load_pltmap()
    mu, d = P.setup(BIN, pm)
    rows = collect(mu)
    print("/* generated by gen_rowtab.py -- (label_off, src_y, page, row) */")
    print("static const rowdef_t ROWTAB[] = {")
    for n, (off, y, pid, i) in enumerate(rows):
        o = "OFF_ANY" if off == OFF_ANY else "0x%03x" % off
        print("    {%s,%3d,%d,%2d}," % (o, y, pid, i))
    print("};")
    print("#define ROWTAB_N %d" % len(rows))

if __name__ == "__main__":
    main()
